def draw_confirm(total: int, without_form: list[str]) -> str:
    if without_form:
        names = "\n".join(f"• {n}" for n in without_form)
        return (
            f"Без анкети зараз {len(without_form)} учасн.:\n{names}\n\n"
            f"Вони НЕ потраплять у жеребкування. Провести гру для {total} учасників із анкетами?"
        )
    return f"Всі анкети на місці 👌 Провести жеребкування для {total} учасників?"


def draw_done(delivered: int, total: int, failed_names: list[str]) -> str:
    text = f"Жеребкування проведено! 🎲\nРозіслано отримувачів: {delivered}/{total}."
    if failed_names:
        names = "\n".join(f"• {n}" for n in failed_names)
        text += (
            f"\n\nНе отримали (бот заблокований або не запущений):\n{names}\n\n"
            "Попроси їх відкрити бота й натисни «Повторити недоставлені»."
        )
    return text


