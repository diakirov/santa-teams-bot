def help_text(role: str, retention: int, limits: tuple[int, int] | None = None) -> str:
    text = _HELP_BASE
    if role == "kerivnyk" and limits:
        text += _HELP_KERIVNYK.format(teams=limits[0], members=limits[1])
    if role == "admin":
        text += _HELP_ADMIN
    text += (
        "\nПро дані: анкети зберігаються лише для проведення гри. В одноразових "
        "командах після завершення гри анкети одразу зникають в учасників, а тобі "
        f"як організатору архівна копія лишається на {retention} дн. — потім "
        "видаляється остаточно (не пізніше ніж за рік від дати гри).\n"
        "Хочеш видалити свої дані раніше — напиши за контактом в описі бота, "
        "видалимо точково. Питання чи щось не працює — туди ж."
    )
    return text

